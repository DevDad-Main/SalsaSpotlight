const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('api', {
  // launcher
  search: (q) => ipcRenderer.invoke('search', q),
  run: (item, q, reveal) => ipcRenderer.invoke('run', { item, q, reveal }),
  icon: (p) => ipcRenderer.invoke('icon', p),
  resize: (h, w) => ipcRenderer.send('resize', h, w),
  hide: () => ipcRenderer.send('hide'),
  onShown: (cb) => ipcRenderer.on('shown', cb),
  // details panel
  fileInfo: (p) => ipcRenderer.invoke('file-info', p),
  copyPath: (p) => ipcRenderer.send('copy-path', p),
  showProps: (p) => ipcRenderer.send('show-props', p),
  forgetRecent: (p) => ipcRenderer.send('forget', p),
  reindex: () => ipcRenderer.send('reindex'),
  // shared state and settings
  getState: () => ipcRenderer.invoke('state'),
  onState: (cb) => ipcRenderer.on('state', (_e, s) => cb(s)),
  setSetting: (key, val) => ipcRenderer.send('set', key, val),
  toggleWidget: (t) => ipcRenderer.send('toggle-widget', t),
  setWidgetSize: (t, k) => ipcRenderer.send('set-size', t, k),
  arrange: () => ipcRenderer.send('arrange'),
  showTour: () => ipcRenderer.send('show-tour'),
  tourClosed: () => ipcRenderer.send('tour-closed'),
  onShowTour: (cb) => ipcRenderer.on('show-tour', () => cb()),
  openSettings: () => ipcRenderer.send('open-settings'),
  onGoto: (cb) => ipcRenderer.on('goto', (_e, p) => cb(p)),
  checkUpdates: () => ipcRenderer.send('check-updates'),
  installUpdate: () => ipcRenderer.send('install-update'),
  getStartupStatus: () => ipcRenderer.invoke('startup:get'),
  setStartupStatus: (enabled) => ipcRenderer.invoke('startup:set', enabled),
  readLogs: () => ipcRenderer.invoke('logs:read'),
  clearLogs: () => ipcRenderer.send('logs:clear'),
  openLogFolder: () => ipcRenderer.send('logs:open-folder'),
  reset: () => ipcRenderer.send('reset'),
  // widgets
  onVis: (cb) => ipcRenderer.on('vis', (_e, v) => cb(v)),
  onResized: (cb) => ipcRenderer.on('resized', cb),
  onArrange: (cb) => ipcRenderer.on('arrange', cb),
  closeWidget: (type) => ipcRenderer.send('close-widget', type),
  setClickThrough: (ignore) => ipcRenderer.send('set-click-through', ignore),
  widgetMenu: (type) => ipcRenderer.send('widget-menu', type),
  dragStart: () => ipcRenderer.send('drag-start'),
  dragEnd: () => ipcRenderer.send('drag-end'),
  stats: () => ipcRenderer.invoke('stats'),
  specs: () => ipcRenderer.invoke('specs'),
  specsGpu: () => ipcRenderer.invoke('specs-gpu'),
  gpuStats: () => ipcRenderer.invoke('gpu-stats'),
  mediaInfo: () => ipcRenderer.invoke('media-info'),
  mediaControl: (a) => ipcRenderer.send('media-control', a),
  net: () => ipcRenderer.invoke('net'),
  disks: () => ipcRenderer.invoke('disks'),
  weather: (city, units) => ipcRenderer.invoke('weather', city, units),
  topApps: () => ipcRenderer.invoke('top-apps'),
  openPath: (p) => ipcRenderer.send('open-path', p),
  pinApp: (p) => ipcRenderer.send('pin-app', p),
  clipGet: () => ipcRenderer.invoke('clip-get'),
  clipCopy: (i) => ipcRenderer.send('clip-copy', i),
  clipClear: () => ipcRenderer.send('clip-clear'),
  onClip: (cb) => ipcRenderer.on('clip', (_e, l) => cb(l)),
});
